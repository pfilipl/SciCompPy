import random


def random_walk(start=0):
    random.seed()
    x = start
    while True:
        yield x
        x += random.choice([-1, 1])


start = float(input("Enter start position: "))
steps = int(input("Enter generator steps: "))
genNo = int(input("Enter number of generators: "))

results = []
for n in range(genNo):
    gen = random_walk(start)
    for s in range(steps - 1):
        next(gen)
    results.append(next(gen))

results_set = sorted(set(results))
str_size = len(str(max(abs(value) for value in results_set))) + 1
for value in results_set:
    print(f"{str(value).rjust(str_size)}: {'|' * results.count(value)}")

